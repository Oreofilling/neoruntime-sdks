// ---- chaining -------------------------------------------------------------------
TEST(FrameTransform, ChainedCropResizeComposes) {
    Frame f = rgb_frame(8, 6, 0);
    Frame c = f.crop(2, 2, 4, 4);
    Frame r = c.resize(2, 2, "stretch");
    ASSERT_TRUE(r.transform.has_value());
    // Chain: crop (origin -2,-2 scale 1) then resize 4x4->2x2 (scale 0.5).
    EXPECT_EQ(r.transform->src_width, 8);
    EXPECT_EQ(r.transform->src_height, 6);
    EXPECT_DOUBLE_EQ(r.transform->scale_x, 0.5);
    EXPECT_DOUBLE_EQ(r.transform->scale_y, 0.5);
    EXPECT_DOUBLE_EQ(r.transform->origin_x, -1.0);
    EXPECT_DOUBLE_EQ(r.transform->origin_y, -1.0);
}

// ---- FrameHandle lifecycle (memfd stands in for the dma-buf) --------------------
namespace {

std::vector<std::uint8_t> rgb_bytes(int w, int h, std::uint8_t seed) {
    std::vector<std::uint8_t> raw(static_cast<std::size_t>(w) * h * 3);
    for (std::size_t i = 0; i < raw.size(); ++i) raw[i] = seed + static_cast<std::uint8_t>(i);
    return raw;
}

int make_memfd(const std::vector<std::uint8_t>& bytes) {
    int fd = ::memfd_create("test-plane", 0);
    if (fd < 0) return -1;
    std::size_t off = 0;
    while (off < bytes.size()) {
        ssize_t n = ::write(fd, bytes.data() + off, bytes.size() - off);
        if (n <= 0) {
            ::close(fd);
            return -1;
        }
        off += static_cast<std::size_t>(n);
    }
    return fd;
}

}  // namespace

TEST(FrameHandle, MaterializesMemfdPlanesAndFiresReleaseOnce) {
    const int w = 4, h = 2;
    const std::vector<std::uint8_t> plane = rgb_bytes(w, h, 7);
    int releases = 0;
    std::uint64_t released_id = 0;

    auto handle = std::make_shared<FrameHandle>(
        std::vector<int>{make_memfd(plane)},
        std::array<std::uint32_t, 3>{static_cast<std::uint32_t>(w * 3), 0, 0},
        std::array<std::uint32_t, 3>{static_cast<std::uint32_t>(plane.size()), 0, 0},
        /*frame_id=*/42,
        [&](FrameHandle& h) { ++releases; released_id = h.frame_id; },
        w, h, "RGB", 0);

    Frame frame;
    frame.sequence = 1;
    frame.width = w;
    frame.height = h;
    frame.format = "RGB";
    frame.handle = std::move(handle);

    // Lazy materialization: to_array maps the fd, copies, caches.
    cv::Mat arr = frame.to_array();
    ASSERT_FALSE(arr.empty());
    EXPECT_EQ(arr.rows, h);
    EXPECT_EQ(arr.cols, w);
    EXPECT_EQ(arr.at<cv::Vec3b>(0, 0)[0], plane[0]);
    EXPECT_EQ(arr.at<cv::Vec3b>(1, 3)[2], plane.back());

    EXPECT_EQ(releases, 0);
    frame.release();  // idempotent, fires on_release exactly once
    frame.release();
    EXPECT_EQ(releases, 1);
    EXPECT_EQ(released_id, 42u);
    EXPECT_TRUE(frame.handle->closed());
}

TEST(FrameHandle, LastCopyReleases) {
    const int w = 2, h = 2;
    const std::vector<std::uint8_t> plane = rgb_bytes(w, h, 1);
    int releases = 0;

    auto make = [&]() {
        return std::make_shared<FrameHandle>(
            std::vector<int>{make_memfd(plane)},
            std::array<std::uint32_t, 3>{6, 0, 0},
            std::array<std::uint32_t, 3>{static_cast<std::uint32_t>(plane.size()), 0, 0},
            7, [&](FrameHandle&) { ++releases; }, w, h, "RGB", 0);
    };
    std::shared_ptr<FrameHandle> a = make();
    {
        std::shared_ptr<FrameHandle> b = a;  // Frame copies share the handle
        EXPECT_EQ(releases, 0);
    }
    EXPECT_EQ(releases, 0);  // still one owner
    a.reset();
    EXPECT_EQ(releases, 1);  // last copy gone -> release
}

TEST(Frame, ConstPathsWorkOnUnmaterializedHandle) {
    const int w = 2, h = 2;
    const std::vector<std::uint8_t> plane = rgb_bytes(w, h, 3);
    Frame f;
    f.width = w;
    f.height = h;
    f.format = "RGB";
    f.handle = std::make_shared<FrameHandle>(
        std::vector<int>{make_memfd(plane)},
        std::array<std::uint32_t, 3>{6, 0, 0},
        std::array<std::uint32_t, 3>{static_cast<std::uint32_t>(plane.size()), 0, 0},
        9, nullptr, w, h, "RGB", 0);

    // crop/resize/to_jpeg_bytes are const and must not cache into `image`.
    const Frame& cf = f;
    Frame cropped = cf.crop(0, 0, 2, 1);
    EXPECT_EQ(cropped.height, 1);
    EXPECT_TRUE(f.image.empty());  // source untouched

    std::vector<std::uint8_t> jpeg = cf.to_jpeg_bytes();
    ASSERT_GE(jpeg.size(), 3u);
    EXPECT_EQ(jpeg[0], 0xFF);  // SOI
    EXPECT_EQ(jpeg[1], 0xD8);
    EXPECT_TRUE(f.image.empty());  // still untouched (const contract)
}

