// crop/resize (port of the pure-logic half of python tests/test_media_ext.py).
//
// Two layers are pinned here:
//   1. detail::resize_geometry against a ground-truth table generated from
//      Python's frame._resize_geometry (the single placement truth the CPU
//      path, the DSP fast path and preprocessing must agree on), and
//   2. Frame::crop/resize pixel-level behavior — canvas padding, content
//      placement, even-dimension guards, AffineTransform math and chaining —
//      plus FrameHandle lifecycle on memfd-backed "dma-bufs".
