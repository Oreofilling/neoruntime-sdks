TEST(FrameCrop, Nv12CropCarriesChromaPlane) {
    Frame f = nv12_frame(8, 4, 0);
    Frame c = f.crop(2, 2, 4, 2);
    ASSERT_FALSE(c.image.empty());
    EXPECT_EQ(c.image.rows, 2 * 3 / 2);  // Y (2) + UV (1)
    EXPECT_EQ(c.image.cols, 4);
    // Chroma row is neutral 128 from the source UV plane.
    EXPECT_EQ(c.image.at<std::uint8_t>(2, 0), 128);
}

// ---- Frame::resize -------------------------------------------------------------
TEST(FrameResize, LetterboxPadsCanvasAndPlacesContent) {
    // 8x6 -> 4x4 letterbox: content 4x3 at (0,0) (floor-division offsets —
    // verified against python _resize_geometry: (4, 3, 0, 0)); row 3 is the
    // only pad row (114).
    Frame f = rgb_frame(8, 6, 0);
    Frame r = f.resize(4, 4, "letterbox", 114);
    ASSERT_FALSE(r.image.empty());
    EXPECT_EQ(r.width, 4);
    EXPECT_EQ(r.height, 4);
    EXPECT_EQ(r.image.rows, 4);
    EXPECT_EQ(r.image.cols, 4);
    for (int x = 0; x < 4; ++x) {
        for (int ch = 0; ch < 3; ++ch) {
            EXPECT_EQ(r.image.at<cv::Vec3b>(3, x)[ch], 114) << "bottom pad row";
        }
    }
    // Content rows 0-2: source blue channel is the constant seed (0) in every
    // pixel, so any averaged content blue is 0 — content, not pad.
    EXPECT_EQ(r.image.at<cv::Vec3b>(0, 0)[2], 0);
    EXPECT_EQ(r.image.at<cv::Vec3b>(2, 3)[2], 0);
    ASSERT_TRUE(r.transform.has_value());
    EXPECT_EQ(r.transform->op, "resize");
    EXPECT_EQ(r.transform->mode, "letterbox");
    EXPECT_DOUBLE_EQ(r.transform->scale_x, 0.5);
    EXPECT_DOUBLE_EQ(r.transform->scale_y, 0.5);
    EXPECT_DOUBLE_EQ(r.transform->origin_x, 0.0);
    EXPECT_DOUBLE_EQ(r.transform->origin_y, 0.0);  // (4-3)//2 == 0
}

