TEST(FrameResize, CropModeCoversAndCenters) {
    // 8x6 -> 4x4 crop: content scaled to cover (5x4 window, python truth
    // (5, 4, 0, 0)), a 4x4 window read out at (0, 0).
    Frame f = rgb_frame(8, 6, 0);
    Frame r = f.resize(4, 4, "crop");
    EXPECT_EQ(r.image.rows, 4);
    EXPECT_EQ(r.image.cols, 4);
    ASSERT_TRUE(r.transform.has_value());
    EXPECT_EQ(r.transform->mode, "crop");
    // crop: scale to cover -> rw = round(8 * max(4/8, 4/6)) = round(16/3) = 5,
    // rh = round(6 * 2/3) = 4; window offset (5-4)//2 = (4-4)//2 = 0.
    EXPECT_DOUBLE_EQ(r.transform->scale_x, 5.0 / 8.0);
    EXPECT_DOUBLE_EQ(r.transform->scale_y, 4.0 / 6.0);
    EXPECT_DOUBLE_EQ(r.transform->origin_x, 0.0);
    EXPECT_DOUBLE_EQ(r.transform->origin_y, 0.0);
}

